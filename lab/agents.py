def director_system(exp_context: str | None, cfg=None, extra: str = "") -> str:
    s = rules_text() + "\n\n---\n\n" + DIRECTOR + "\n\n" + stt_knowledge("director")
    if cfg is not None:
        from .growth import context_for
        learned = context_for(cfg, "director")
        if learned:
            s += "\n\n" + learned
